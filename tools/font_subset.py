"""Collect the code points the patch must bake into its CJK font atlases.

A full CJK face is tens of thousands of glyphs, far more than one atlas holds. The translation only ever uses a few
thousand, so this tool scans the patched tables and the game's remaining text assets and writes the exact subset as
`fonts/truetype/cjk_glyphs.txt`, one hexadecimal code point per line (the format the atlas loader reads).

ASCII and Latin-1 always come from the face's own CP1252 block, so only text above U+02FF is listed.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Iterable

TEXT_SUFFIXES = {".txt", ".lua", ".yml", ".yaml", ".ini", ".json", ".csv"}
FIRST_SUBSET_CODE_POINT = 0x0300


def code_points_of(path: Path) -> Iterable[int]:
    try:
        text = path.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError):
        return ()

    return (ord(character) for character in text)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--patch", type=Path, required=True, help="patch asset root (mod directory)")
    parser.add_argument("--openyamm", type=Path, required=True, help="OpenYAMM checkout")
    parser.add_argument("--out", type=Path, required=True, help="fonts/truetype directory to write the subset into")
    arguments = parser.parse_args()

    roots = [arguments.patch / "engine/data_tables", arguments.openyamm / "assets_dev"]
    found: set[int] = set()

    for root in roots:
        if not root.exists():
            continue

        for path in root.rglob("*"):
            if path.suffix.lower() not in TEXT_SUFFIXES or not path.is_file():
                continue
            found.update(point for point in code_points_of(path) if point >= FIRST_SUBSET_CODE_POINT)

    arguments.out.mkdir(parents=True, exist_ok=True)
    subset_path = arguments.out / "cjk_glyphs.txt"
    lines = ["# Code points baked into the CJK atlases; regenerated by tools/font_subset.py."]
    lines.extend(f"{point:04x}" for point in sorted(found))
    subset_path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="")

    print(f"{len(found)} code points written to {subset_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
